#!/usr/bin/env python3
"""Rebuild tides.js from LINZ's official standard-port tide tables.

The dashboard reads tides.js directly (LINZ's files don't allow cross-origin
browser requests, so they can't be fetched live). LINZ publishes each year's
tables in advance - re-run this before the last year in YEARS runs out, adding
new years as they appear. Stdlib only.
"""
import csv
import io
import json
import urllib.parse
import urllib.request
from datetime import date

PORTS = ["Gisborne", "Auckland", "Marsden Point", "Wellington", "Lyttelton", "Bluff", "Port Taranaki"]
YEARS = [2026, 2027, 2028]
URL = "https://static.charts.linz.govt.nz/tide-tables/maj-ports/csv/{}.csv"


def fetch_events(port, year):
    url = URL.format(urllib.parse.quote(f"{port} {year}"))
    with urllib.request.urlopen(url) as res:
        text = res.read().decode("utf-8-sig")
    events = []
    for row in csv.reader(io.StringIO(text)):
        # Data rows: day, weekday, month, year, then up to 4 time,height pairs.
        # The first 3 lines are headers, which have no numeric year in column 4.
        if len(row) < 6 or not row[3].strip().isdigit():
            continue
        iso = date(int(row[3]), int(row[2]), int(row[0])).isoformat()
        for i in range(4, len(row) - 1, 2):
            if row[i].strip():
                events.append((iso, row[i].strip(), float(row[i + 1])))
    return events


def main():
    today = date.today().isoformat()
    tables = {}
    for port in PORTS:
        events = [e for year in YEARS for e in fetch_events(port, year)]
        days = {}
        for i, (iso, hhmm, height) in enumerate(events):
            # The tables don't label highs and lows, but they strictly alternate.
            neighbour = events[i + 1] if i + 1 < len(events) else events[i - 1]
            kind = "H" if height > neighbour[2] else "L"
            if iso >= today:
                days.setdefault(iso, []).append(f"{kind}{hhmm} {height}")
        tables[port] = {iso: ",".join(items) for iso, items in days.items()}
        print(f"{port}: {len(days)} days")

    with open("tides.js", "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by update_tides.py - do not edit by hand.\n")
        f.write("// Source: Land Information New Zealand. Crown Copyright Reserved.\n")
        f.write("// Times are NZ local (standard or daylight); heights in metres above chart datum.\n")
        f.write("const LINZ_TIDES = ")
        json.dump(tables, f, separators=(",", ":"))
        f.write(";\n")


if __name__ == "__main__":
    main()
